def build_gazetteers_for_language(lang: str, gazetteer_dir: Path) -> dict[str, int]:
    """Write deduplicated person, place, and org gazetteer lists for a language."""
    lang_dir = gazetteer_dir / lang
    lang_dir.mkdir(parents=True, exist_ok=True)

    entities = GAZETTEER_REGISTRY.get(lang, {})
    counts: dict[str, int] = {}

    for cat in ["persons", "places", "orgs"]:
        items = entities.get(cat, [])
        # Deduplicate while preserving order
        seen: set[str] = set()
        deduped: list[str] = []
        for item in items:
            cleaned = item.strip()
            if cleaned and cleaned not in seen:
                seen.add(cleaned)
                deduped.append(cleaned)

        file_path = lang_dir / f"{cat}.txt"
        with open(file_path, "w", encoding="utf-8") as f:
            for item in deduped:
                f.write(item + "\n")

        counts[cat] = len(deduped)
        print(f"[{lang.upper()}] Wrote {len(deduped)} entries to {file_path}")

    return counts


def run_gazetteer_building(config_path: str = "configs/base_config.yaml", overrides: list[str] | None = None) -> dict[str, Any]:
    cfg: BaseConfig = load_config(config_path, overrides=overrides)
    set_global_seed(cfg.seed)

    logger = ExperimentLogger(log_dir=cfg.logging.log_dir, backend=cfg.logging.backend)
    gazetteer_dir = PROJECT_ROOT / "data" / "gazetteers"

    stats: dict[str, Any] = {}
    for lang in cfg.project.languages:
        cat_counts = build_gazetteers_for_language(lang, gazetteer_dir)
        for cat, cnt in cat_counts.items():
            stats[f"{lang}_{cat}_count"] = cnt

    logger.log_run(
        config_path=config_path,
        metrics=stats,
        dataset_version="v0.1-gazetteers",
    )
    return stats


