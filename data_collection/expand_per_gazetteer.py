def expand_person_gazetteers() -> dict[str, Any]:
    print("=" * 80)
    print("EXPANDING PERSON-NAME (PER) GAZETTEERS ACROSS ALL THREE LANGUAGES")
    print("=" * 80)

    gaz_dir = PROJECT_ROOT / "data" / "gazetteers"
    additions = {
        "konkani": ADDITIONAL_PERSONS_KONKANI,
        "sinhala": ADDITIONAL_PERSONS_SINHALA,
        "assamese": ADDITIONAL_PERSONS_ASSAMESE,
    }

    results = {}
    for lang, new_names in additions.items():
        p_file = gaz_dir / lang / "persons.txt"
        existing = []
        if p_file.is_file():
            existing = [l.strip() for l in p_file.read_text(encoding="utf-8").splitlines() if l.strip()]

        before_count = len(existing)
        # Deduplicate preserving order
        seen = set(existing)
        expanded = list(existing)
        for name in new_names:
            norm = name.strip()
            if norm and norm not in seen:
                seen.add(norm)
                expanded.append(norm)

        after_count = len(expanded)
        # Save back
        p_file.write_text("\n".join(expanded) + "\n", encoding="utf-8")
        print(f"[{lang.upper()}] Expanded {p_file.name}: {before_count} -> {after_count} entries (+{after_count - before_count})")

        results[lang] = {
            "before": before_count,
            "after": after_count,
            "added": after_count - before_count,
            "path": str(p_file),
        }

    return results


if __name__ == "__main__":
    expand_person_gazetteers()
